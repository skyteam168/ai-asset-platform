"""Emit console TypeScript types from control-plane OpenAPI (G1.4 minimal).

Usage:
  .venv/Scripts/python tools/gen_console_api_types.py
  cd console && npm run gen:api

Output (commit it): console/src/api-types.generated.ts
"""

from __future__ import annotations

import pathlib
from typing import Any

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
OPENAPI = ROOT / "docs" / "api" / "control-plane.openapi.yaml"
OUT = ROOT / "console" / "src" / "api-types.generated.ts"

WANT = ("UpstreamMcpSource", "UpstreamMcpPreviewHash", "Asset", "ConnectionTestResult")


def json_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _inline_object(schema: dict[str, Any]) -> str:
    props = schema.get("properties") or {}
    if not props:
        return "Record<string, unknown>"
    required = set(schema.get("required") or [])
    fields: list[str] = []
    for key, prop in props.items():
        if not isinstance(prop, dict):
            continue
        opt = "?" if key not in required else ""
        fields.append(f"{key}{opt}: {_ts_type(prop)}")
    return "{ " + "; ".join(fields) + " }"


def _ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "enum" in schema:
        parts: list[str] = []
        for v in schema["enum"]:
            if v is None:
                parts.append("null")
            elif isinstance(v, bool):
                parts.append("true" if v else "false")
            elif isinstance(v, str):
                parts.append(json_str(v))
            else:
                parts.append(str(v))
        return " | ".join(parts)
    t = schema.get("type")
    if isinstance(t, list):
        return " | ".join(_ts_type({"type": x}) for x in t)
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "array":
        items = schema.get("items") or {}
        if isinstance(items, dict) and ("properties" in items or items.get("type") == "object"):
            return f"Array<{_inline_object(items)}>"
        return f"Array<{_ts_type(items) if isinstance(items, dict) else 'unknown'}>"
    if t == "object" or "properties" in schema:
        return _inline_object(schema) if schema.get("properties") else "Record<string, unknown>"
    if t == "null":
        return "null"
    return "unknown"


def _object(schema: dict[str, Any], *, name: str) -> str:
    props = schema.get("properties") or {}
    required = set(schema.get("required") or [])
    lines = [f"export interface {name} {{"]
    for key, prop in props.items():
        if not isinstance(prop, dict):
            continue
        opt = "" if key in required else "?"
        typ = _ts_type(prop)
        lines.append(f"  {key}{opt}: {typ};")
    lines.append("}")
    return "\n".join(lines)


def _emit_connection() -> str:
    # SystemConnection is an external JSON Schema $ref in OpenAPI; pin console response shape here.
    return """/** System connection list/detail (conn.schemas.SystemConnection + required id/status). */
export interface SystemConnection {
  id: string;
  company_id: string;
  system_key: string;
  env: "sandbox" | "test" | "staging" | "prod" | string;
  base_url: string;
  scheme: "https" | "http" | "postgres" | "mysql";
  tls_mode?: "system_ca" | "custom_ca" | "pinned" | "insecure" | null;
  pins: Array<{ kind: "cert" | "spki"; sha256: string }>;
  transport_exception_reason: string | null;
  transport_exception_expires_at: string | null;
  transport_approved_by: string[];
  tls_last_seen_fingerprint?: string | null;
  status: "pending_approval" | "active" | "disabled" | string;
}
"""


def main() -> None:
    doc = yaml.safe_load(OPENAPI.read_text(encoding="utf-8"))
    schemas: dict[str, Any] = (doc.get("components") or {}).get("schemas") or {}
    chunks = [
        "/* eslint-disable */",
        "/** AUTO-GENERATED by tools/gen_console_api_types.py — do not edit. */",
        "/** Source: docs/api/control-plane.openapi.yaml */",
        "",
        _emit_connection().rstrip(),
        "",
    ]
    for name in WANT:
        schema = schemas.get(name)
        if not isinstance(schema, dict):
            raise SystemExit(f"OpenAPI schema missing: {name}")
        if schema.get("type") == "object" or "properties" in schema:
            chunks.append(_object(schema, name=name))
            chunks.append("")
        else:
            raise SystemExit(f"unsupported schema shape: {name}")
    OUT.write_text("\n".join(chunks).rstrip() + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
